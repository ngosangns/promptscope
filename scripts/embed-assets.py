#!/usr/bin/env python3
"""Regenerate Swift string constants from schemas/v1 and skills/promptscope.

The JSON files and SKILL.md are the source of truth. Run this after editing them.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "schemas" / "v1"
SKILL = ROOT / "skills" / "promptscope"
SWIFT_SCHEMAS = ROOT / "macos" / "Sources" / "PromptscopeKit" / "Schemas.swift"
SWIFT_SKILL = ROOT / "macos" / "Sources" / "PromptscopeKit" / "EmbeddedSkill.swift"


def swift_string(text: str) -> str:
    if not text.endswith("\n"):
        text += "\n"
    # A blank line keeps the file's trailing newline inside the raw string.
    return '#"""\n' + text + '\n"""#'


def write_schemas() -> None:
    names = sorted(path.stem for path in SCHEMAS.glob("*.json"))
    parts = [
        "import Foundation",
        "",
        "/// JSON Schema documents (draft 2020-12) embedded in the CLI.",
        "/// Generated by scripts/embed-assets.py from schemas/v1. Do not edit.",
        "public enum EmbeddedSchemas {",
    ]
    for name in names:
        body = (SCHEMAS / f"{name}.json").read_text(encoding="utf-8")
        ident = name.replace("-", "_")
        parts.append(f"    public static let {ident} = {swift_string(body)}")
        parts.append("")
    parts.append("    public static func text(named name: String) -> String? {")
    parts.append("        switch name {")
    for name in names:
        ident = name.replace("-", "_")
        parts.append(f'        case "{name}": {ident}')
    parts.append("        default: nil")
    parts.append("        }")
    parts.append("    }")
    parts.append("}")
    parts.append("")
    SWIFT_SCHEMAS.write_text("\n".join(parts), encoding="utf-8")


def write_skill() -> None:
    files = sorted(
        path.relative_to(SKILL).as_posix()
        for path in SKILL.rglob("*")
        if path.is_file() and not any(part.startswith(".") for part in path.relative_to(SKILL).parts)
    )
    parts = [
        "import Foundation",
        "",
        "/// Skill files embedded in the CLI.",
        "/// Generated by scripts/embed-assets.py from skills/promptscope. Do not edit.",
        "public enum EmbeddedSkill {",
        "    public static let files: [String: String] = [",
    ]
    for name in files:
        body = (SKILL / name).read_text(encoding="utf-8")
        parts.append(f"        {swift_quote(name)}: {swift_string(body)},")
    parts.append("    ]")
    parts.append("}")
    parts.append("")
    SWIFT_SKILL.write_text("\n".join(parts), encoding="utf-8")


def swift_quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    write_schemas()
    write_skill()
    print(f"wrote {SWIFT_SCHEMAS.name} and {SWIFT_SKILL.name}")
